"use client";

import React, { useState } from "react";
import {
  Copy,
  Check,
  Download,
  Sparkles,
  Layers,
  Film,
  FileText,
  Megaphone,
  ShieldCheck,
  Info,
} from "lucide-react";

export default function CreativeStudioSection({
  audiences,
  marketingAngles,
  selectedAngleId,
  setSelectedAngleId,
  selectedAudienceId,
  setSelectedAudienceId,
  campaignOutputs,
  onInspectEvidenceById,
}) {
  const [copiedKey, setCopiedKey] = useState(null);
  const [activeTab, setActiveTab] = useState("all"); // 'all', 'ad', 'listing', 'storyboard'

  // Retrieve campaign output based on selected angle and audience
  const currentAngleOutputs = campaignOutputs[selectedAngleId] || campaignOutputs["monsoon-barrier"];
  const currentData = currentAngleOutputs[selectedAudienceId] || currentAngleOutputs["gen-z"];

  const activeAngle = marketingAngles.find((a) => a.id === selectedAngleId) || marketingAngles[0];
  const activeAudience = audiences.find((a) => a.id === selectedAudienceId) || audiences[0];

  function copyToClipboard(text, key) {
    if (!navigator.clipboard) return;
    navigator.clipboard.writeText(text);
    setCopiedKey(key);
    setTimeout(() => {
      setCopiedKey(null);
    }, 2000);
  }

  function handleExportMarkdown() {
    const mdContent = `# Proof2Pitch AI: Grounded Campaign Package
## Product: Dot & Key Dragon Fruit Bounce Gel Sunscreen SPF 50+ PA++++
**Strategic Marketing Angle:** ${activeAngle.name}
**Target Audience:** ${activeAudience.label}
**Date Generated:** ${new Date().toLocaleDateString()}

---

### 1. High-Converting Ad Copy (Meta / Instagram)
**Hook:**
${currentData.adCopy.hook}

**Primary Ad Body:**
${currentData.adCopy.primaryText}

**Visual Art Direction Note:**
${currentData.adCopy.artDirection}

**Call to Action:**
${currentData.adCopy.cta}

**Provenance & Grounding:**
${currentData.adCopy.provenanceNote}

---

### 2. E-Commerce Product Listing (Amazon / Nykaa A+ Content)
**Headline:**
${currentData.pdpListing.headline}

**Key Feature Bullets:**
${currentData.pdpListing.bulletPoints.map((bp) => `- ${bp}`).join("\n")}

**Compliance Disclaimer:**
${currentData.pdpListing.complianceDisclaimer}

---

### 3. Four-Panel Promotional Storyboard
${currentData.storyboard
  .map(
    (f) => `#### Frame ${f.frameNumber}: ${f.sceneTitle}
- Visual Action: ${f.visualAction}
- Audio/Voiceover: ${f.spokenAudio}
- On-Screen Text: ${f.onScreenText}
- Evidence Citation: [${f.evidenceTag}]
`
  )
  .join("\n")}

---
*Generated by Proof2Pitch AI Studio for Dot & Key. All claims anchored to verifiable evidence records.*
`;

    const blob = new Blob([mdContent], { type: "text/markdown;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = `dot-and-key-${selectedAngleId}-${selectedAudienceId}-campaign.md`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  }

  return (
    <div className="space-y-8">
      {/* Header and Controls */}
      <div className="p-6 bg-app-card rounded-2xl border border-line-subtle shadow-clay-sm space-y-6">
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 pb-4 border-b border-line-subtle">
          <div>
            <h2 className="font-serif text-2xl sm:text-3xl font-bold text-ink-primary">
              Creative Campaign Studio
            </h2>
            <p className="text-xs sm:text-sm text-ink-muted mt-1">
              Produce evidence-backed ad copy, e-commerce listings, and video storyboards directly from verified market research.
            </p>
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={handleExportMarkdown}
              className="inline-flex items-center gap-2 px-4 py-2.5 rounded-xl bg-app-subtle border border-line-subtle text-ink-primary hover:bg-app-card hover:border-line-strong text-xs font-semibold transition-all shadow-clay-sm focus-visible:ring-2 focus-visible:ring-terracotta"
            >
              <Download className="w-4 h-4 text-terracotta" />
              <span>Export as Markdown</span>
            </button>
          </div>
        </div>

        {/* Dynamic Selectors */}
        <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
          {/* Angle Selector */}
          <div className="space-y-2">
            <label className="text-xs font-mono font-semibold uppercase tracking-wider text-ink-muted block">
              1. Selected Marketing Opportunity Angle
            </label>
            <div className="flex flex-col gap-2">
              {marketingAngles.map((angle) => {
                const isSelected = selectedAngleId === angle.id;
                return (
                  <button
                    key={angle.id}
                    onClick={() => setSelectedAngleId(angle.id)}
                    className={`p-3 rounded-xl border text-left transition-all ${
                      isSelected
                        ? "bg-terracotta/10 border-terracotta ring-1 ring-terracotta shadow-clay-sm"
                        : "bg-app-subtle border-line-subtle hover:bg-app-card"
                    }`}
                  >
                    <div className="flex items-center justify-between">
                      <span className="text-xs font-bold text-ink-primary">{angle.name}</span>
                      {isSelected && (
                        <span className="text-[10px] px-2 py-0.5 rounded bg-terracotta text-ink-inverted font-semibold">
                          Active Angle
                        </span>
                      )}
                    </div>
                    <p className="text-[11px] text-ink-muted italic mt-0.5">
                      &ldquo;{angle.headline}&rdquo;
                    </p>
                  </button>
                );
              })}
            </div>
          </div>

          {/* Audience Selector */}
          <div className="space-y-2">
            <label className="text-xs font-mono font-semibold uppercase tracking-wider text-ink-muted block">
              2. Target Audience Segment
            </label>
            <div className="flex flex-col gap-2">
              {audiences.map((aud) => {
                const isSelected = selectedAudienceId === aud.id;
                return (
                  <button
                    key={aud.id}
                    onClick={() => setSelectedAudienceId(aud.id)}
                    className={`p-3 rounded-xl border text-left transition-all ${
                      isSelected
                        ? "bg-sage/10 border-sage ring-1 ring-sage shadow-clay-sm"
                        : "bg-app-subtle border-line-subtle hover:bg-app-card"
                    }`}
                  >
                    <div className="flex items-center justify-between">
                      <span className="text-xs font-bold text-ink-primary">{aud.label}</span>
                      {isSelected && (
                        <span className="text-[10px] px-2 py-0.5 rounded bg-sage-dark text-ink-inverted font-semibold">
                          Target Segment
                        </span>
                      )}
                    </div>
                    <p className="text-[11px] text-ink-muted mt-0.5">{aud.focusText}</p>
                  </button>
                );
              })}
            </div>
          </div>
        </div>

        {/* Provenance Banner */}
        <div className="p-3.5 rounded-xl bg-status-success-bg border border-sage/30 flex flex-col sm:flex-row sm:items-center justify-between gap-2 text-xs text-status-success">
          <div className="flex items-center gap-2">
            <ShieldCheck className="w-4 h-4 shrink-0" />
            <span className="font-semibold">
              Grounding Integrity Verified:
            </span>
            <span className="text-ink-primary">
              All copy blocks below reference verifiable research evidence IDs.
            </span>
          </div>
          <div className="flex items-center gap-1.5 flex-wrap">
            {activeAngle.supportingEvidence.map((evId) => (
              <button
                key={evId}
                onClick={() => onInspectEvidenceById(evId)}
                className="font-mono text-[10px] px-2 py-0.5 rounded bg-app-card text-ink-primary border border-line-subtle hover:bg-terracotta hover:text-ink-inverted transition-colors"
                title="Inspect evidence source"
              >
                [{evId}]
              </button>
            ))}
          </div>
        </div>
      </div>

      {/* Campaign Deliverables Tabs */}
      <div className="flex items-center gap-2 bg-app-subtle p-1 rounded-xl border border-line-subtle w-fit">
        {[
          { id: "all", label: "Full Campaign View", icon: Layers },
          { id: "ad", label: "Ad Copy", icon: Megaphone },
          { id: "listing", label: "E-Commerce PDP", icon: FileText },
          { id: "storyboard", label: "Promotional Storyboard", icon: Film },
        ].map((tab) => {
          const Icon = tab.icon;
          const isActive = activeTab === tab.id;
          return (
            <button
              key={tab.id}
              onClick={() => setActiveTab(tab.id)}
              className={`flex items-center gap-1.5 px-3.5 py-1.5 rounded-lg text-xs font-medium transition-all ${
                isActive
                  ? "bg-app-card text-ink-primary shadow-clay-sm font-semibold"
                  : "text-ink-muted hover:text-ink-primary"
              }`}
            >
              <Icon className="w-3.5 h-3.5" />
              <span>{tab.label}</span>
            </button>
          );
        })}
      </div>

      {/* Deliverable 1: Ad Copy */}
      {(activeTab === "all" || activeTab === "ad") && (
        <div className="p-6 rounded-2xl bg-app-card border border-line-subtle shadow-clay-sm space-y-5">
          <div className="flex items-center justify-between pb-3 border-b border-line-subtle">
            <div className="flex items-center gap-2">
              <Megaphone className="w-5 h-5 text-terracotta" />
              <h3 className="font-serif text-xl font-bold text-ink-primary">
                1. High-Converting Meta and Instagram Ad Copy
              </h3>
            </div>
            <button
              onClick={() =>
                copyToClipboard(
                  `HOOK:\n${currentData.adCopy.hook}\n\nBODY:\n${currentData.adCopy.primaryText}\n\nCTA: ${currentData.adCopy.cta}`,
                  "ad"
                )
              }
              className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-app-subtle border border-line-subtle text-xs font-semibold text-ink-primary hover:bg-app-card transition-all"
            >
              {copiedKey === "ad" ? (
                <>
                  <Check className="w-3.5 h-3.5 text-status-success" />
                  <span className="text-status-success">Copied!</span>
                </>
              ) : (
                <>
                  <Copy className="w-3.5 h-3.5 text-ink-muted" />
                  <span>Copy Ad Copy</span>
                </>
              )}
            </button>
          </div>

          <div className="space-y-4 text-xs">
            {/* Hook */}
            <div className="p-4 rounded-xl bg-app-subtle border border-line-subtle space-y-1">
              <span className="text-[10px] font-mono font-bold uppercase tracking-wider text-terracotta block">
                Primary Ad Hook (Problem-Agitate-Solve)
              </span>
              <p className="font-serif text-base font-bold text-ink-primary leading-snug">
                &ldquo;{currentData.adCopy.hook}&rdquo;
              </p>
            </div>

            {/* Primary Text */}
            <div className="space-y-1">
              <span className="text-[10px] font-mono font-bold uppercase tracking-wider text-ink-muted block">
                Primary Text Body
              </span>
              <p className="text-sm text-ink-primary leading-relaxed bg-app-bg p-4 rounded-xl border border-line-subtle">
                {currentData.adCopy.primaryText}
              </p>
            </div>

            {/* Visual Art Direction */}
            <div className="p-3.5 rounded-xl bg-sand-light border border-line-subtle text-ink-primary space-y-1">
              <span className="text-[10px] font-mono font-bold uppercase tracking-wider text-ink-muted block">
                Creative Art Direction Note
              </span>
              <p className="text-xs leading-relaxed italic">{currentData.adCopy.artDirection}</p>
            </div>

            {/* CTA and Provenance */}
            <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 pt-2">
              <div className="flex items-center gap-2">
                <span className="text-[11px] font-semibold text-ink-muted">Suggested CTA:</span>
                <span className="px-3 py-1 rounded-lg bg-terracotta text-ink-inverted font-semibold text-xs">
                  {currentData.adCopy.cta}
                </span>
              </div>
              <span className="text-[11px] text-ink-muted italic">
                {currentData.adCopy.provenanceNote}
              </span>
            </div>
          </div>
        </div>
      )}

      {/* Deliverable 2: E-Commerce Product Listing */}
      {(activeTab === "all" || activeTab === "listing") && (
        <div className="p-6 rounded-2xl bg-app-card border border-line-subtle shadow-clay-sm space-y-5">
          <div className="flex items-center justify-between pb-3 border-b border-line-subtle">
            <div className="flex items-center gap-2">
              <FileText className="w-5 h-5 text-terracotta" />
              <h3 className="font-serif text-xl font-bold text-ink-primary">
                2. Amazon and Nykaa A+ Product Listing Content
              </h3>
            </div>
            <button
              onClick={() =>
                copyToClipboard(
                  `${currentData.pdpListing.headline}\n\n${currentData.pdpListing.bulletPoints.join(
                    "\n"
                  )}\n\n${currentData.pdpListing.complianceDisclaimer}`,
                  "pdp"
                )
              }
              className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-app-subtle border border-line-subtle text-xs font-semibold text-ink-primary hover:bg-app-card transition-all"
            >
              {copiedKey === "pdp" ? (
                <>
                  <Check className="w-3.5 h-3.5 text-status-success" />
                  <span className="text-status-success">Copied!</span>
                </>
              ) : (
                <>
                  <Copy className="w-3.5 h-3.5 text-ink-muted" />
                  <span>Copy Listing</span>
                </>
              )}
            </button>
          </div>

          <div className="space-y-4 text-xs">
            {/* Listing Headline */}
            <div>
              <span className="text-[10px] font-mono font-bold uppercase tracking-wider text-ink-muted block mb-1">
                Optimized PDP Headline
              </span>
              <h4 className="font-serif text-lg font-bold text-ink-primary">
                {currentData.pdpListing.headline}
              </h4>
            </div>

            {/* Bullets */}
            <div className="space-y-2">
              <span className="text-[10px] font-mono font-bold uppercase tracking-wider text-ink-muted block">
                Evidence-Anchored Feature Bullets
              </span>
              <ul className="space-y-2">
                {currentData.pdpListing.bulletPoints.map((bp, i) => (
                  <li
                    key={i}
                    className="p-3.5 rounded-xl bg-app-bg border border-line-subtle text-xs text-ink-primary leading-relaxed flex items-start gap-2.5"
                  >
                    <span className="w-5 h-5 rounded-full bg-terracotta/10 text-terracotta font-bold text-xs flex items-center justify-center shrink-0 mt-0.5">
                      {i + 1}
                    </span>
                    <span>{bp}</span>
                  </li>
                ))}
              </ul>
            </div>

            {/* Compliance Disclaimer */}
            <div className="p-3 bg-app-subtle rounded-lg border border-line-subtle text-[11px] text-ink-muted flex items-center gap-2">
              <ShieldCheck className="w-4 h-4 text-sage-dark shrink-0" />
              <span>{currentData.pdpListing.complianceDisclaimer}</span>
            </div>
          </div>
        </div>
      )}

      {/* Deliverable 3: 4-Panel Visual Storyboard */}
      {(activeTab === "all" || activeTab === "storyboard") && (
        <div className="p-6 rounded-2xl bg-app-card border border-line-subtle shadow-clay-sm space-y-5">
          <div className="flex items-center justify-between pb-3 border-b border-line-subtle">
            <div className="flex items-center gap-2">
              <Film className="w-5 h-5 text-terracotta" />
              <h3 className="font-serif text-xl font-bold text-ink-primary">
                3. Four-Panel Promotional Storyboard
              </h3>
            </div>
            <button
              onClick={() =>
                copyToClipboard(
                  currentData.storyboard
                    .map(
                      (f) =>
                        `Frame ${f.frameNumber}: ${f.sceneTitle}\nVisual: ${f.visualAction}\nAudio: ${f.spokenAudio}\nText: ${f.onScreenText}\nEvidence: [${f.evidenceTag}]`
                    )
                    .join("\n\n"),
                  "storyboard"
                )
              }
              className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-app-subtle border border-line-subtle text-xs font-semibold text-ink-primary hover:bg-app-card transition-all"
            >
              {copiedKey === "storyboard" ? (
                <>
                  <Check className="w-3.5 h-3.5 text-status-success" />
                  <span className="text-status-success">Copied!</span>
                </>
              ) : (
                <>
                  <Copy className="w-3.5 h-3.5 text-ink-muted" />
                  <span>Copy Storyboard</span>
                </>
              )}
            </button>
          </div>

          <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-4 gap-4">
            {currentData.storyboard.map((frame) => (
              <div
                key={frame.frameNumber}
                className="p-4 rounded-xl bg-app-bg border border-line-subtle flex flex-col justify-between space-y-3 shadow-clay-sm"
              >
                <div className="space-y-2 text-xs">
                  <div className="flex items-center justify-between">
                    <span className="font-mono text-xs font-bold text-terracotta px-2 py-0.5 rounded bg-terracotta/10">
                      Frame 0{frame.frameNumber}
                    </span>
                    <button
                      onClick={() => onInspectEvidenceById(frame.evidenceTag)}
                      className="font-mono text-[10px] px-1.5 py-0.5 rounded bg-app-subtle border border-line-subtle text-ink-muted hover:text-terracotta"
                      title="Inspect evidence link"
                    >
                      [{frame.evidenceTag}]
                    </button>
                  </div>

                  <h4 className="font-serif text-sm font-bold text-ink-primary">
                    {frame.sceneTitle}
                  </h4>

                  <div className="space-y-1.5">
                    <div>
                      <span className="text-[10px] font-mono text-ink-muted block uppercase">
                        Visual Action
                      </span>
                      <p className="text-[11px] text-ink-primary leading-relaxed">
                        {frame.visualAction}
                      </p>
                    </div>

                    <div>
                      <span className="text-[10px] font-mono text-ink-muted block uppercase">
                        Audio / Script
                      </span>
                      <p className="text-[11px] text-ink-muted italic leading-relaxed">
                        {frame.spokenAudio}
                      </p>
                    </div>
                  </div>
                </div>

                <div className="pt-2 border-t border-line-subtle">
                  <span className="text-[10px] font-mono text-ink-muted block uppercase">
                    On-Screen Super
                  </span>
                  <p className="text-[11px] font-semibold text-terracotta">
                    {frame.onScreenText}
                  </p>
                </div>
              </div>
            ))}
          </div>
        </div>
      )}
    </div>
  );
}
